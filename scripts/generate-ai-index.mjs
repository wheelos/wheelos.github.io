import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const roots = ['about', 'knowledge', 'resources', 'practice', 'evidence', 'organization', 'roadmap']
const pages = []

async function collect(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name)
    if (entry.isDirectory()) await collect(path)
    else if (entry.name.endsWith('.md') && !entry.name.startsWith('_')) pages.push(path)
  }
}

for (const root of roots) await collect(root)
pages.unshift('index.md')
pages.sort((a, b) => (a === 'index.md' ? -1 : b === 'index.md' ? 1 : a.localeCompare(b)))

const sections = ['# WheelOS Docs — AI-readable content', '', '> This file is generated by `npm run docs:generate-ai`. It contains the current Markdown source for citation and retrieval.', '']
for (const path of pages) {
  const source = await readFile(path, 'utf8')
  const title = source.match(/^#\s+(.+)$/m)?.[1] ?? path
  sections.push(`## ${title}`, '', `<!-- source: ${path} -->`, '', source.trim(), '', '---', '')
}

await writeFile('public/llms-full.txt', sections.join('\n'))
await mkdir('public/evidence', { recursive: true })
await writeFile('public/evidence/registry.json', await readFile('evidence/registry.json'))
await writeFile('public/catalog.json', await readFile('knowledge/catalog.json'))
console.log(`generated public/llms-full.txt from ${pages.length} pages`)
